interface SET_SLEEP_OPTIONS {
    Timeout: number
}

export const SetSleep = async ({ Timeout }: SET_SLEEP_OPTIONS): Promise<void> => {
    return new Promise((resolve) => {
        setTimeout(resolve, Timeout );
    });
}