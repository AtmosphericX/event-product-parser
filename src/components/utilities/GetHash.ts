import { createHash } from "node:crypto"

interface GET_VALUES_OPTIONS {
    Input: string
    Salt?: string
}

export const GetHash = ({ Input, Salt = '' }: GET_VALUES_OPTIONS): string => {
    return createHash('sha256').update(Input + Salt).digest('hex');
}