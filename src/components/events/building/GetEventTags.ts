import { ENUM_TAGS } from "@Enums.Properties/Tags"

interface GET_EVENT_TAGS_OPTIONS {
    Message: string
}

export const GetEventTags = ({ Message }: GET_EVENT_TAGS_OPTIONS): string[] => {
    return [...new Set(Object.values(ENUM_TAGS)
        .flat()
        .filter(({ Match }) => Match.test(Message))
        .map(({ Label }) => Label)
    )];
}